# Ana tiene 8 manzanas y compra 5 más. ¿Cuántas manzanas tiene ahora?
#================================================

A = 8 #Manzana
C = 5 #Compradas
X = (A + C)

print("Ecuacion #1")
print(f"A = {A}\nC = {C}\n")
print("Ecuacion (A + C) = X")
print(f"Resultado ({A} + {C}) = {X}\n")

