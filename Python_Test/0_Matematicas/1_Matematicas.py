#================================================
# Marta tenía 40 caramelos. Regaló 12 a un amigo y después compró 25 más. ¿Cuántos caramelos tiene ahora?
#================================================

C = 40 #Caramelos
R = 12 #Regalo
M = 25 #Mas caramelos
T = (C - R) + M #Total

print("Ecuacion #4")
print(f"C = {C}\nR = {R}\nM = {M}\n")
print("Ecuacion (C - R) = T")
print(f"Resultado ({C} - {R}) = {T}")

#================================================
# Una tienda tiene 240 botellas de agua. Durante la mañana vende 75 y por la tarde vende el doble de lo que vendió 
# por la mañana. ¿Cuántas botellas quedan al final del día?
#================================================

I = 240 #Inventario de botellas
M = 75  #Ventas Manana
T = 2*M #Ventas Tarde
VT = (M + T) #Ventas totales
IR = (I - VT) #Inventario restante

print("Ecuacion #5")
print(f"I = {I}\nM = {M}\nT = {T}\n")

print("Ecuacion (2 * M) = T")
print(f"Ecuacion (2 * {M}) = {T}\n")

print("Ecuacion (M + T) = VT")
print(f"Ecuacion ({M} + {T}) = {VT}\n")

print("Ecuacion (I - VT) = IR")
print(f"Ecuacion ({I} - {VT}) = {IR}\n")

#================================================
# Un agricultor plantó 18 filas de árboles y en cada fila hay 14 árboles. Después, decidió añadir 56 árboles más. 
